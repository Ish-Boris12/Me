function showView(requestedView, updateHistory) {
    const viewName = pageNames.has(requestedView) ? requestedView : "home";
    pageViews.forEach((view) => {
        view.hidden = view.dataset.pageView !== viewName;
    });

    navLinks.querySelectorAll("[data-view-target]").forEach((link) => {
        const active = link.dataset.viewTarget === viewName;
        link.classList.toggle("active", active);
        if (active) link.setAttribute("aria-current", "page");
        else link.removeAttribute("aria-current");
    });

    navLinks.classList.remove("open");
    menuButton.setAttribute("aria-expanded", "false");
    menuButton.setAttribute("aria-label", translations[currentLanguage].openMenu);
    window.scrollTo(0, 0);
    if (updateHistory && window.location.hash !== `#${viewName}`) {
        window.history.pushState({ view: viewName }, "", `#${viewName}`);
    }
}

document.querySelectorAll("[data-view-target]").forEach((link) => {
    link.addEventListener("click", (event) => {
        event.preventDefault();
        showView(link.dataset.viewTarget, true);
    });
});

