form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const copy = translations[currentLanguage];
    const invalidField = form.querySelector(":invalid");
    if (invalidField) {
        formStatus.textContent = copy.formRequired;
        formStatus.classList.add("error");
        invalidField.focus();
        return;
    }

    const submitButton = form.querySelector("button[type='submit']");
    submitButton.disabled = true;
    submitButton.textContent = copy.formSending;
    formStatus.textContent = "";
    formStatus.classList.remove("error");

    try {
        const response = await fetch("/api/requests", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify(Object.fromEntries(new FormData(form))),
        });
        const result = await response.json();
        if (!response.ok) {
            const error = new Error(result.error || copy.formConnection);
            error.code = result.code;
            throw error;
        }

        formStatus.textContent = copy.formSuccess;
        form.reset();
        submitButton.textContent = copy.formSuccess;
        window.setTimeout(() => {
            closeModal();
            formStatus.textContent = "";
            submitButton.textContent = copy.formSend;
            submitButton.disabled = false;
        }, 2200);
    } catch (error) {
        const messageKey = serviceErrorKeys[error.code];
        formStatus.textContent = messageKey ? copy[messageKey] : copy.formConnection;
        formStatus.classList.add("error");
        submitButton.textContent = copy.formRetry;
        submitButton.disabled = false;
    }
});
