function showService(name, focusTab) {
    serviceTabs.forEach((tab) => {
        const selected = tab.dataset.serviceTab === name;
        tab.classList.toggle("active", selected);
        tab.setAttribute("aria-selected", String(selected));
        tab.tabIndex = selected ? 0 : -1;
        if (selected && focusTab) tab.focus();
    });
    servicePanels.forEach((panel) => {
        panel.hidden = panel.dataset.servicePanel !== name;
    });
}

serviceTabs.forEach((tab, index) => {
    tab.addEventListener("click", () => showService(tab.dataset.serviceTab, false));
    tab.addEventListener("keydown", (event) => {
        let nextIndex = index;
        if (event.key === "ArrowRight") nextIndex = (index + 1) % serviceTabs.length;
        else if (event.key === "ArrowLeft") nextIndex = (index - 1 + serviceTabs.length) % serviceTabs.length;
        else if (event.key === "Home") nextIndex = 0;
        else if (event.key === "End") nextIndex = serviceTabs.length - 1;
        else return;
        event.preventDefault();
        showService(serviceTabs[nextIndex].dataset.serviceTab, true);
    });
});

function dismissSplash() {
    if (splash.hidden || splash.classList.contains("is-hidden")) return;
    splash.classList.add("is-hidden");
    window.setTimeout(() => {
        splash.hidden = true;
    }, 420);
}

