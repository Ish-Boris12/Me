function getPreferredLanguage() {
    try {
        const savedLanguage = localStorage.getItem("ib-ltd-language");
        if (supportedLanguages.has(savedLanguage)) return savedLanguage;
    } catch (error) {
        console.warn("Could not read the saved language preference.", error);
    }

    for (const browserLanguage of navigator.languages || [navigator.language]) {
        const languageCode = browserLanguage.split("-")[0].toLowerCase();
        if (supportedLanguages.has(languageCode)) return languageCode;
    }
    return "en";
}

function getPreferredTheme() {
    try {
        const savedTheme = localStorage.getItem("ib-ltd-theme");
        if (savedTheme === "light" || savedTheme === "dark") return savedTheme;
    } catch (error) {
        console.warn("Could not read the saved theme preference.", error);
    }

    return window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark";
}

let currentLanguage = getPreferredLanguage();
let currentTheme = getPreferredTheme();

function updateThemeControl() {
    const isDark = currentTheme === "dark";
    const copy = translations[currentLanguage];
    themeToggle.setAttribute("aria-pressed", String(isDark));
    themeToggle.setAttribute("aria-label", copy[isDark ? "switchToLight" : "switchToDark"]);
    themeToggleLabel.textContent = copy[isDark ? "themeLight" : "themeDark"];
    themeSymbol.textContent = isDark ? "☼" : "☾";
}

function applyTheme(theme, savePreference) {
    currentTheme = theme === "light" ? "light" : "dark";
    document.documentElement.dataset.theme = currentTheme;
    themeColorMeta.setAttribute("content", currentTheme === "dark" ? "#0d202f" : "#f7fafb");
    updateThemeControl();

    if (savePreference) {
        try {
            localStorage.setItem("ib-ltd-theme", currentTheme);
        } catch (error) {
            console.warn("Could not save the theme preference.", error);
        }
    }
}

function applyLanguage(language) {
    currentLanguage = supportedLanguages.has(language) ? language : "en";
    const copy = translations[currentLanguage];

    document.documentElement.lang = currentLanguage;
    document.title = copy.pageTitle;
    languageSelect.value = currentLanguage;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        if (copy[key]) element.textContent = copy[key];
    });

    document.querySelectorAll("*").forEach((element) => {
        Array.from(element.attributes).forEach((attribute) => {
            if (!attribute.name.startsWith("data-i18n-")) return;
            const targetAttribute = attribute.name.slice("data-i18n-".length);
            const translation = copy[attribute.value];
            if (translation) element.setAttribute(targetAttribute, translation);
        });
    });

    const menuIsOpen = navLinks.classList.contains("open");
    menuButton.setAttribute("aria-label", copy[menuIsOpen ? "closeMenu" : "openMenu"]);
    updateThemeControl();
}

